"""
mds_cluster_efficiency.py -- probabilities of DT and CSC muon-detector-shower (MDS) clusters for long-lived particles
(LLPs), for recasting the CMS searches EXO-21-008 (DT + CSC) and EXO-20-015 (CSC), with all maps embedded.

Pure Python (only `math` and `random`): no ROOT, numpy or Delphes needed. It is the reference implementation of what the
Delphes card cards/delphes_card_CMS_MDSCluster_HV_filtered_v2_v6.tcl does (plus the overlap treatment below, not yet in
Delphes). GENERATED by scripts/make_mds_cluster_efficiency_py.py (dt_parametrization_claude); do not edit the maps by hand.

Units: lengths in mm (as in Delphes), energies in GeV.

Input, one dict per LLP (generator level; LLPs whose decay products are all invisible are not passed in):
    x, y, z          decay position [mm]
    px, py, pz       LLP momentum [GeV] (only its direction is used)
    Eem              energy of the visible decay products that are e, gamma or pi0 [GeV]
    Ehad             energy of the other visible decay products (neutrinos, muons and invisible BSM states excluded) [GeV]
    multiplicity     number of visible decay products counted in Eem + Ehad

Categories and maps:
    loose (2-tag, EXO-21-008 double-cluster selections) -- maps derived for this study (2-tag v6):
        DT : |eta| < 2.4, 2950 < r < 7380, |z| < 6710; regions Solenoid / MB1 (central |z| < 4000, forward), MB2, MB34;
             maps in (multiplicity, Eem, Ehad)
        CSC: |eta| < 2.4, r < 6955, 4000 < |z| < 11000; regions a (r >= 3900), b (|z| >= 6710), c (r < 2950),
             d (2950 <= r < 3900); maps in (Eem, Ehad)
    tight (1-tag, single-cluster selections), as in the Delphes card:
        DT : |eta| < 2.4, 4500 < r < 7380, |z| < 6710; regions MB2, MB34; maps (1-tag v2) in (multiplicity, Eem, Ehad)
        CSC: |eta| < 2.0, r < 6955, 4000 < |z| < 11000; probability = cut-based ID efficiency x official Delphes CSC
             cluster map, regions a (r > 3900, |z| < 6710) and b (|z| > 6710), 0 elsewhere
    Bins: values below the first edge go to the first bin, above the last edge to the last bin. The maps are valid for
    LLPs that are isolated (validated for two LLPs with deltaR > 0.8).

Overlapping LLPs (cluster_efficiency_delphes_studies.ipynb):
    - LLPs decaying inside the DT or CSC loose acceptance are grouped when deltaR(LLP_i, LLP_j) < MERGE_DR (= 0.6),
      chained (A close to B and B close to C -> one group): close LLPs give at most one cluster per detector.
    - A group gives a cluster in a detector with P = 1 - prod_i (1 - p_i), each member with its own map (p_i = 0 outside
      the acceptance); for an isolated LLP this is its map value.
    - Tight only: if a member of the group decays in a vetoed volume (in front of MB1, or at small radius in the endcap),
      its decay products trigger the MB1 / ME1 vetoes of the tight selections and the group gets P_tight = 0.

One random number per group (assign_clusters): u uniform in [0, 1); a DT cluster if u < P_DT, a CSC cluster if
u > 1 - P_CSC, so a group never gets both (if P_DT + P_CSC > 1 both are scaled down to sum to 1, and flagged). The same u
is used for the loose and the tight categories, so a tight cluster comes with a loose one whenever P_tight <= P_loose
(flagged otherwise): in the full simulation, tight clusters are a subset of loose ones.

Run `python mds_cluster_efficiency.py` for worked examples.
"""
