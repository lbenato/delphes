def _derived(llp):
    """r, |z|, eta, phi of an LLP dict (eta as in Delphes' CscClusterId: +-999.9 along the beam)."""
    x, y, z = llp['x'], llp['y'], llp['z']
    px, py, pz = llp['px'], llp['py'], llp['pz']
    pt = math.hypot(px, py)
    eta = (999.9 if pz >= 0 else -999.9) if pt == 0 else math.asinh(pz / pt)
    return math.hypot(x, y), abs(z), eta, math.atan2(py, px)


def delta_r(llp1, llp2):
    _, _, eta1, phi1 = _derived(llp1)
    _, _, eta2, phi2 = _derived(llp2)
    dphi = abs(phi1 - phi2)
    if dphi > math.pi:
        dphi = 2 * math.pi - dphi
    return math.hypot(eta1 - eta2, dphi)


