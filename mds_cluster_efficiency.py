def make_llp(r, z, eta, phi, Eem, Ehad, multiplicity):
    """LLP dict from decay radius / z [mm], direction (eta, phi) and visible energies [GeV]."""
    pt = 10.0
    return dict(x=r * math.cos(phi), y=r * math.sin(phi), z=z, px=pt * math.cos(phi), py=pt * math.sin(phi),
                pz=pt * math.sinh(eta), Eem=Eem, Ehad=Ehad, multiplicity=multiplicity)


def _show(title, llps, seed=1):
    print(f'\n=== {title}')
    for i, l in enumerate(llps):
        r, az, eta, phi = _derived(l)
        p = llp_probabilities(l)
        regs = ', '.join(f"{d} {s}: {p[(d, s)][0] or '-'} {p[(d, s)][1]:.3f}" for d in ('DT', 'CSC') for s in ('loose', 'tight'))
        print(f'  LLP {i}: r = {r:.0f} mm, |z| = {az:.0f} mm, eta = {eta:+.2f}, phi = {phi:+.2f}, Eem = {l["Eem"]:.0f}, '
              f'Ehad = {l["Ehad"]:.0f}, mult = {l["multiplicity"]} | {regs}')
    rng = random.Random(seed)
    for g in assign_clusters(llps, rng):
        P = ', '.join(f'P_{d},{s} = {g["P"][(d, s)]:.3f}' for s in ('loose', 'tight') for d in ('DT', 'CSC'))
        print(f'  group {g["members"]}: {P}; u = {g["u"]:.3f} -> loose: {g["loose"][0] or "no cluster"}'
              + (f' (LLP {g["loose"][1]})' if g['loose'][0] else '') + f', tight: {g["tight"][0] or "no cluster"}'
              + (f' (LLP {g["tight"][1]})' if g['tight'][0] else ''))
        for f in g['flags']:
            print(f'    note: {f}')


