def in_muon_system(llp):
    """LLPs that can leave hits in the muon system: decay inside the DT or CSC loose acceptance."""
    r, az, eta, _ = _derived(llp)
    return dt_loose_region(r, az, eta) is not None or csc_loose_region(r, az, eta) is not None


def group_llps(llps, max_dr=MERGE_DR):
    """Indices of the LLPs in the muon system, grouped by deltaR < max_dr (chained); other LLPs are left out."""
    idx = [i for i, l in enumerate(llps) if in_muon_system(l)]
    parent = {i: i for i in idx}

    def find(i):
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i
    for a in range(len(idx)):
        for b in range(a + 1, len(idx)):
            if delta_r(llps[idx[a]], llps[idx[b]]) < max_dr:
                parent[find(idx[a])] = find(idx[b])
    groups = {}
    for i in idx:
        groups.setdefault(find(i), []).append(i)
    return sorted(groups.values())


def group_probabilities(llps, group):
    """Probabilities of one group: {(det, sel): P}, the members' own values, and flags."""
    probs = [llp_probabilities(llps[i]) for i in group]
    out, flags = {}, []
    for det in ('DT', 'CSC'):
        for sel in ('loose', 'tight'):
            q = 1.0
            for p in probs:
                q *= 1.0 - p[(det, sel)][1]
            P = 1.0 - q
            if sel == 'tight':
                vetoing = [i for i in group if in_tight_veto_volume(det, *_derived(llps[i])[:2])]
                if vetoing and P > 0:
                    flags.append(f'{det} tight vetoed by LLP {vetoing}')
                    P = 0.0
            out[(det, sel)] = P
    for sel in ('loose', 'tight'):
        s = out[('DT', sel)] + out[('CSC', sel)]
        if s > 1.0:
            flags.append(f'P_DT + P_CSC = {s:.3f} > 1 ({sel}): both scaled down')
            out[('DT', sel)] /= s; out[('CSC', sel)] /= s
    for det in ('DT', 'CSC'):
        if out[(det, 'tight')] > out[(det, 'loose')]:
            flags.append(f'{det}: P_tight > P_loose (a tight cluster may come without a loose one)')
    return out, probs, flags


def assign_clusters(llps, rng=random):
    """One random number per group -> clusters. Returns one dict per group: members, probabilities, u, and for each
    category ('loose', 'tight') the detector of its cluster ('DT', 'CSC' or None) and the representative LLP (the member
    with the largest probability in that detector)."""
    results = []
    for group in group_llps(llps):
        P, probs, flags = group_probabilities(llps, group)
        u = rng.random()
        res = dict(members=group, P=P, u=u, flags=flags)
        for sel in ('loose', 'tight'):
            det = 'DT' if u < P[('DT', sel)] else ('CSC' if u > 1.0 - P[('CSC', sel)] else None)
            rep = None
            if det:
                rep = max(zip(group, probs), key=lambda gp: gp[1][(det, sel)][1])[0]
            res[sel] = (det, rep)
        results.append(res)
    return results


