def dt_loose_region(r, az, eta):
    if not (abs(eta) < 2.4 and 2950.0 < r < 7380.0 and az < 6710.0):
        return None
    if r < 3900.0:
        return 'Solenoid_central' if az < 4000.0 else 'Solenoid_forward'
    if r < 4500.0:
        return 'MB1_central' if az < 4000.0 else 'MB1_forward'
    return 'MB2' if r < 5330.0 else 'MB34'


def csc_loose_region(r, az, eta):
    if not (abs(eta) < 2.4 and r < 6955.0 and 4000.0 < az < 11000.0):
        return None
    if az >= 6710.0:
        return 'b'
    if r >= 3900.0:
        return 'a'
    return 'c' if r < 2950.0 else 'd'


def dt_tight_region(r, az, eta):
    if not (abs(eta) < 2.4 and 4500.0 < r < 7380.0 and az < 6710.0):
        return None
    return 'MB2' if r < 5330.0 else 'MB34'


def csc_tight_region(r, az, eta):
    # CSCFilter acceptance of the card; the ID and the map are non-zero only in a and b
    if not (abs(eta) < 2.0 and 0.0 < r < 6955.0 and 4000.0 < az < 11000.0):
        return None
    if r > 3900.0 and az < 6710.0:
        return 'a'
    if az > 6710.0:
        return 'b'
    return 'c'


def in_tight_veto_volume(det, r, az):
    """Decay volumes outside the tight acceptance whose showers trigger the vetoes of the tight selections (MB1 hits for
    DT; MB1 segments, RB1 and ME1/1-1/2 hits for CSC): a group with a member decaying here gets P_tight = 0 in that
    detector. DT: in front of MB1 and in MB1 (Solenoid / MB1). CSC: the endcap at small radius (CSC c / d) and the
    Solenoid / MB1 volume outside CSC region a."""
    if det == 'DT':
        return 2950.0 <= r < 4500.0 and az < 6710.0
    return (r < 3900.0 and 4000.0 < az < 6710.0) or (2950.0 <= r < 4500.0 and az < 4000.0)


# ------------------------------------------------------------------------------------------------------------------
# map lookups
# ------------------------------------------------------------------------------------------------------------------
def _bin(x, edges):
    """Bin index with the first and last bins open-ended (as np.clip(np.digitize(x, edges[1:-1]), 0, n - 1))."""
    i = 0
    for e in edges[1:-1]:
        if x >= e:
            i += 1
    return i


def _grid(region_map, mult, eem, ehad):
    sub = region_map['maps'][_bin(mult, region_map['mult_edges'])]
    return sub['eff'][_bin(eem, sub['eem_edges'])][_bin(ehad, sub['ehad_edges'])]


_CSC_EEM_EDGES = [0.0, 25.0, 50.0, 75.0, 100.0, 125.0, 150.0]
_CSC_EHAD_EDGES = [0.0, 25.0, 50.0, 75.0, 100.0, 150.0, 200.0]


def _csc_ehad_row(ehad):
    """E_had row of the official CSC map / N-station table: 0 for E_had == 0, then (0, 25), [25, 50), ..., [200, inf)."""
    if ehad < 0.0:
        return None
    if ehad == 0.0:
        return 0
    row = 1
    for e in _CSC_EHAD_EDGES[1:]:
        if ehad >= e:
            row += 1
    return row


def csc_eta_cut(r, az):
    """eta cut of single-station CSC clusters (EtaCutFormula of the card)."""
    if az < 6320.0 or (az < 7240.0 and r > 2750.0):
        return 1.8
    return 1.6 if az < 9700.0 else 1.8


def p_csc_tight_parts(r, az, eta, eem, ehad):
    """(P_ID, P_map) of the tight CSC chain of the Delphes card; P_CSC,tight = P_ID * P_map."""
    reg = csc_tight_region(r, az, eta)
    row = _csc_ehad_row(ehad)
    if reg not in ('a', 'b') or row is None or eem < 0.0:
        return 0.0, 0.0
    n_station = CSC_TIGHT_NSTATION[reg][row]
    p_id = n_station * (abs(eta) < CSC_TIGHT_ETA_MAX) + (1.0 - n_station) * (abs(eta) < csc_eta_cut(r, az))
    j = 0
    for e in _CSC_EEM_EDGES[1:]:
        if eem >= e:
            j += 1
    return p_id, CSC_TIGHT_MAP[reg][j][row]


def llp_probabilities(llp):
    """Cluster probabilities of one LLP, as if isolated: {('DT'|'CSC', 'loose'|'tight'): (region or None, p)}."""
    r, az, eta, _ = _derived(llp)
    eem, ehad, mult = llp['Eem'], llp['Ehad'], llp['multiplicity']
    out = {}
    reg = dt_loose_region(r, az, eta)
    out[('DT', 'loose')] = (reg, _grid(DT_LOOSE[reg], mult, eem, ehad) if reg else 0.0)
    reg = csc_loose_region(r, az, eta)
    out[('CSC', 'loose')] = (reg, _grid(CSC_LOOSE[reg], mult, eem, ehad) if reg else 0.0)
    reg = dt_tight_region(r, az, eta)
    out[('DT', 'tight')] = (reg, _grid(DT_TIGHT[reg], mult, eem, ehad) if reg else 0.0)
    reg = csc_tight_region(r, az, eta)
    p_id, p_map = p_csc_tight_parts(r, az, eta, eem, ehad)
    out[('CSC', 'tight')] = (reg, p_id * p_map)
    return out


